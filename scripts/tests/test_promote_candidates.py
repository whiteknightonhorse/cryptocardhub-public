# --- CCH-KW-03 step 3: a keyword already on a page is not a new cluster -----

def _page(path, primary, supporting):
    path.write_text(
        f'---\ntitle: "t"\nprimary_keyword: {json.dumps(primary)}\n'
        f'supporting_keywords: {json.dumps(supporting)}\n---\nbody\n', encoding="utf-8")


def _run_promote(tmp_path, monkeypatch, query, bank_text):
    (tmp_path / "CANDIDATES.md").write_text(
        "# Keyword candidates\n\n- fetched: `2026-10-19T00:00:00+00:00`\n\n"
        "## New-page candidates\n\n"
        "| query | impressions | clicks | proposed slug | measurement |\n|---|---|---|---|---|\n"
        f"| {query} | 90 | 1 | `x` | impressions 90 / clicks 1 / window ..2026-10-19 / bing-webmaster |\n",
        encoding="utf-8")
    (tmp_path / "SKILL.md").write_text(bank_text, encoding="utf-8")
    for name, attr in (("CANDIDATES.md", "CANDIDATES"), ("SKILL.md", "BANK"), ("ledger.jsonl", "LEDGER")):
        monkeypatch.setattr(pc, attr, tmp_path / name)
    monkeypatch.setattr(pc, "PSEO_DIR", tmp_path / "pages")
    monkeypatch.setattr(sys, "argv", ["promote-candidates.py"])
    pc.main()
    ledger = tmp_path / "ledger.jsonl"
    return [json.loads(l) for l in ledger.read_text(encoding="utf-8").splitlines() if l.strip()]


def test_promote_refuses_a_candidate_already_a_supporting_keyword_of_a_page(tmp_path, monkeypatch):
    (tmp_path / "pages").mkdir()
    _page(tmp_path / "pages" / "gemini-card-review.md", "gemini card review", ["gemini credit card", "x y"])
    led = _run_promote(tmp_path, monkeypatch, "Gemini Credit Card", SAMPLE_BANK)
    assert any(e.get("event") == "refused" and e.get("reason") == "covered_by_page_keyword" for e in led)
    assert not any(e.get("event") == "promoted" for e in led)


def test_promote_refuses_everything_when_a_page_has_an_unexpected_frontmatter_shape(tmp_path, monkeypatch):
    (tmp_path / "pages").mkdir()
    (tmp_path / "pages" / "odd.md").write_text("---\nprimary_keyword: x\n---\n", encoding="utf-8")
    led = _run_promote(tmp_path, monkeypatch, "crypto card complaints", SAMPLE_BANK)
    assert any(e.get("reason") == "page_keyword_unreadable" for e in led)
    assert not any(e.get("event") == "promoted" for e in led)
