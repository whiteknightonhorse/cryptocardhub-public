"""G-PROMOTE (2026-09-01) — CANDIDATES.md -> the keyword bank, gated in code.

FIRST: pin CANDIDATES.md's format. bing-keywords.py (the writer) and this
file's `parse_candidates` (the reader) are the two "siblings" named in the
prior sweep — the queue and its parser drifted apart there the same way a
writer and a future reader always can. The fixture below is copied verbatim
from the real, live CANDIDATES.md on 2026-08-31 (fetched by bing-keywords.py
itself) — if bing-keywords.py's `render()` ever changes this shape, this
test goes red before promote-candidates.py silently mis-parses it.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent


def _load(name, relpath):
    spec = importlib.util.spec_from_file_location(name, ROOT / relpath)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod   # pseo-generate.py's @dataclass needs this pre-registered
    spec.loader.exec_module(mod)
    return mod


pc = _load("promote_candidates", "scripts/promote-candidates.py")

# --- the pinned format: verbatim from the real CANDIDATES.md, 2026-08-31 ---
REAL_CANDIDATES_MD = """# Keyword candidates — measured demand, not yet bank rows

Generated by `scripts/bing-keywords.py`. **`parse_keyword_bank()` does not read this
file.** A candidate becomes a bank row only by deliberate promotion into SKILL.md,
carrying its number, window and instrument — a query that merely exists is not demand.

- fetched: `2026-08-31T05:40:02.621113+00:00`
- queries returned by Bing: **137**
- already covered by a page: 3
- below 10 impressions: 123
- off transactional intent: 1
- **candidates: 10**

| query | impressions | clicks | proposed slug | measurement |
|---|---|---|---|---|
| binance card usage for everyday purchases | 82 | 2 | `binance-card-usage-for-everyday-purchases` | impressions 82 / clicks 2 / window ..2026-08-31 / bing-webmaster |
| credit card vs crypto card for daily expenses | 79 | 3 | `credit-card-vs-crypto-card-for-daily-expenses` | impressions 79 / clicks 3 / window ..2026-08-31 / bing-webmaster |
| crypto rebates vs cashback: which is better? | 77 | 1 | `crypto-rebates-vs-cashback-which-is-better` | impressions 77 / clicks 1 / window ..2026-08-31 / bing-webmaster |
| binance card | 10 | 0 | `binance-card` | impressions 10 / clicks 0 / window ..2026-08-31 / bing-webmaster |
"""


def test_parse_candidates_pins_the_real_format(tmp_path):
    p = tmp_path / "CANDIDATES.md"
    p.write_text(REAL_CANDIDATES_MD, encoding="utf-8")
    data = pc.parse_candidates(p)
    assert data["fetched_at"] == "2026-08-31T05:40:02.621113+00:00"
    assert len(data["rows"]) == 4
    first = data["rows"][0]
    assert first == {
        "query": "binance card usage for everyday purchases",
        "impressions": 82, "clicks": 2,
        "slug": "binance-card-usage-for-everyday-purchases",
        "measurement": "impressions 82 / clicks 2 / window ..2026-08-31 / bing-webmaster",
    }


def test_parse_candidates_handles_the_empty_no_candidates_case(tmp_path):
    """bing-keywords.py's render() writes a prose paragraph, not a table,
    when zero candidates clear its filters. Must parse as zero rows, not
    crash and not silently swallow a real row from elsewhere in the file."""
    p = tmp_path / "CANDIDATES.md"
    p.write_text(
        "# Keyword candidates\n\n- fetched: `2026-08-24T05:40:00+00:00`\n"
        "- candidates: **0**\n\n"
        "_No candidate cleared the filters. That is an answer, not a failure:_\n"
        "_a zero here means the measured demand is already served._\n",
        encoding="utf-8")
    data = pc.parse_candidates(p)
    assert data["rows"] == []
    assert data["fetched_at"] == "2026-08-24T05:40:00+00:00"


def test_parse_candidates_on_a_missing_file_is_empty_not_an_error(tmp_path):
    data = pc.parse_candidates(tmp_path / "does-not-exist.md")
    assert data == {"fetched_at": None, "rows": []}


