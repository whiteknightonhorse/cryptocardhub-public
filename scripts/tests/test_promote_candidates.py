def test_bucket_weight_zero_query_is_never_added_to_eligible(tmp_path, monkeypatch):
    """The G81 defect reproduced and fixed: a 'binance card usage for everyday
    purchases'-shaped new-page candidate (bucket G, weight 0) must never reach
    the bank, however many confirmed impressions it carries."""
    candidates_md = (
        "# Keyword candidates\n\n- fetched: `2026-09-14T00:00:00+00:00`\n\n"
        "## New-page candidates\n\n"
        "| query | impressions | clicks | proposed slug | measurement |\n"
        "|---|---|---|---|---|\n"
        "| crypto card usage for everyday spending | 215 | 4 | "
        "`crypto-card-usage-for-everyday-spending` | impressions 215 / clicks 4 "
        "/ window ..2026-09-14 / bing-webmaster |\n"
    )
    monkeypatch.setattr(pc, "CANDIDATES", tmp_path / "CANDIDATES.md")
    monkeypatch.setattr(pc, "BANK", tmp_path / "SKILL.md")
    monkeypatch.setattr(pc, "LEDGER", tmp_path / "ledger.jsonl")
    (tmp_path / "CANDIDATES.md").write_text(candidates_md, encoding="utf-8")
    (tmp_path / "SKILL.md").write_text(SAMPLE_BANK, encoding="utf-8")
    monkeypatch.setattr(sys, "argv", ["promote-candidates.py"])
    pc.main()
    bank_after = (tmp_path / "SKILL.md").read_text(encoding="utf-8")
    assert "crypto card usage for everyday spending" not in bank_after
    ledger_lines = [json.loads(l) for l in
                    (tmp_path / "ledger.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    assert any(e.get("event") == "refused" and e.get("reason") == "bucket_weight_zero"
              for e in ledger_lines)


